package Main;

/**
 *
 * @author Usuario
 */
public class Student {
    private int id;
    private String nombre;
    private float nota;

    public Student(int id, String nombre, float nota) {
        this.id = id;
        this.nombre = nombre;
        this.nota = nota;
    }

    public int getId() {
        return id;
    }

    public String getNombre() {
        return nombre;
    }

    public float getNota() {
        return nota;
    }
    
    
    
    
    
}
